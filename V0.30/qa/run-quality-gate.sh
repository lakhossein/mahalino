#!/usr/bin/env bash
# V0.30 acceptance and release gate. Only a zero exit code permits publication.
set -Eeuo pipefail
repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$repo_root"
result_dir="${QA_RESULTS_DIR:-$repo_root/V0.30/qa/results}"
mkdir -p "$result_dir"
export QA_RESULTS_DIR="$result_dir"
export QA_BASE_URL="${QA_BASE_URL:-http://127.0.0.1:8730/Mahalino%2BV0.30.html}"

# Catch malformed JS even in code paths not reached by browser tests.
for js in V0.30/build_v030.js V0.30/src/*.js V0.30/qa/smoke-v030.js V0.30/qa/e2e-*.js V0.30/qa/*.cjs; do
  node --check "$js"
done

# Every v30 artifact must be regenerated by the checked-in build and match it.
before_build_sha="$(sha256sum 'V0.30/Mahalino+V0.30.html' | cut -d ' ' -f 1)"
node V0.30/build_v030.js
after_build_sha="$(sha256sum 'V0.30/Mahalino+V0.30.html' | cut -d ' ' -f 1)"
if [[ "$before_build_sha" != "$after_build_sha" ]]; then
  echo "ERROR: V0.30 HTML changed on rebuilding. Update generated HTML and sources together."
  exit 1
fi
# A dirty checkout is acceptable only for local diagnostics explicitly opted in
# by the developer; CI never opts in and therefore must test committed output.
if [[ "${QA_ALLOW_DIRTY_WORKTREE:-0}" != 1 ]] && ! git diff --quiet -- V0.30/Mahalino+V0.30.html; then
  echo "ERROR: V0.30 HTML differs from reproducible build output. Commit both sources and generated HTML."
  git diff --stat -- V0.30/Mahalino+V0.30.html
  exit 1
fi

# Standalone archive contract: only V0.30/base + V0.30/src + build script.
# This intentionally does NOT provide ../V0.29, catching hidden dependencies.
standalone_dir="$(mktemp -d)"
cleanup_standalone(){
  if [[ -n "$standalone_dir" && "$standalone_dir" != / && -d "$standalone_dir" ]]; then
    rm -rf -- "$standalone_dir"
  fi
}
trap cleanup_standalone EXIT
mkdir -p "$standalone_dir/V0.30"
cp V0.30/build_v030.js "$standalone_dir/V0.30/"
cp -R V0.30/src V0.30/base "$standalone_dir/V0.30/"
node "$standalone_dir/V0.30/build_v030.js"
if ! cmp -s "$standalone_dir/V0.30/Mahalino+V0.30.html" V0.30/Mahalino+V0.30.html; then
  echo "ERROR: standalone V0.30 build differs from repository version."
  exit 1
fi
cleanup_standalone
trap - EXIT

# Static resources must exist and must not be zero-byte placeholders.
node V0.30/qa/check-assets.cjs >"$result_dir/asset-manifest.json"

python3 -m http.server 8730 --bind 127.0.0.1 --directory V0.30 >"$result_dir/http-server.log" 2>&1 &
server_pid=$!
trap 'kill "$server_pid" 2>/dev/null || true' EXIT
ready=0
for _attempt in $(seq 1 35); do
  if curl -fsS "$QA_BASE_URL" -o /dev/null; then ready=1; break; fi
  sleep 1
done
if test "$ready" -ne 1; then
  echo "ERROR: local HTTP server did not serve the exact V0.30 HTML"
  exit 1
fi

failed_suites=0
for suite in smoke-v030.js e2e-functional.js e2e-conversational.js v030-browser-regressions.cjs e2e-acceptance-v030.cjs e2e-scenarios-v030.cjs e2e-full-journeys-v030.cjs; do
  echo "========= $suite ========="
  if node "V0.30/qa/$suite" >"$result_dir/$suite.log" 2>&1; then
    echo "PASS $suite"
  else
    echo "FAIL $suite"
    failed_suites=$((failed_suites+1))
  fi
  tail -n 30 "$result_dir/$suite.log"
done
if node V0.30/qa/check-coverage.cjs >"$result_dir/coverage-gate.log" 2>&1; then
  echo "PASS machine-readable §19.1 coverage gate"
else
  echo "FAIL mandatory §19.1 coverage gate"
  failed_suites=$((failed_suites+1))
fi
tail -n 12 "$result_dir/coverage-gate.log"
echo "Release gate: $failed_suites failing suite(s)."
if test "$failed_suites" -ne 0; then
  echo "REFUSING PUBLICATION: every QA suite must pass."
  exit 1
fi
echo "ALL GATES PASS: V0.30 may be published."
