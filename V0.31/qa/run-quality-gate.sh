#!/usr/bin/env bash
# V0.31 acceptance and release gate. Only a zero exit code permits publication.
set -Eeuo pipefail
repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$repo_root"
result_dir="${QA_RESULTS_DIR:-$repo_root/V0.31/qa/results}"
mkdir -p "$result_dir"
export QA_RESULTS_DIR="$result_dir"
export QA_BASE_URL="${QA_BASE_URL:-http://127.0.0.1:8731/Mahalino%2BV0.31.html}"

# Catch malformed JS even in code paths not reached by browser tests.
for js in V0.31/build_v031.js V0.31/src/*.js V0.31/qa/smoke-v031.js V0.31/qa/e2e-*.js V0.31/qa/*.cjs; do
  node --check "$js"
done
node V0.31/qa/check-guidance.cjs
node V0.31/qa/check-build-injection.cjs
node V0.31/qa/check-investment-extraction.cjs
node V0.31/qa/check-guided-results.cjs
node V0.31/qa/check-optional-needs.cjs

# Every v30 artifact must be regenerated by the checked-in build and match it.
before_build_sha="$(sha256sum 'V0.31/Mahalino+V0.31.html' | cut -d ' ' -f 1)"
node V0.31/build_v031.js
after_build_sha="$(sha256sum 'V0.31/Mahalino+V0.31.html' | cut -d ' ' -f 1)"
if [[ "$before_build_sha" != "$after_build_sha" ]]; then
  echo "ERROR: V0.31 HTML changed on rebuilding. Update generated HTML and sources together."
  exit 1
fi
# A dirty checkout is acceptable only for local diagnostics explicitly opted in
# by the developer; CI never opts in and therefore must test committed output.
if [[ "${QA_ALLOW_DIRTY_WORKTREE:-0}" != 1 ]] && ! git diff --quiet -- V0.31/Mahalino+V0.31.html; then
  echo "ERROR: V0.31 HTML differs from reproducible build output. Commit both sources and generated HTML."
  git diff --stat -- V0.31/Mahalino+V0.31.html
  exit 1
fi

# Standalone archive contract: only V0.31/base + V0.31/src + build script.
# This intentionally does NOT provide ../V0.29, catching hidden dependencies.
standalone_dir="$(mktemp -d)"
cleanup_standalone(){
  if [[ -n "$standalone_dir" && "$standalone_dir" != / && -d "$standalone_dir" ]]; then
    rm -rf -- "$standalone_dir"
  fi
}
trap cleanup_standalone EXIT
mkdir -p "$standalone_dir/V0.31"
cp V0.31/build_v031.js "$standalone_dir/V0.31/"
cp -R V0.31/src V0.31/base "$standalone_dir/V0.31/"
node "$standalone_dir/V0.31/build_v031.js"
if ! cmp -s "$standalone_dir/V0.31/Mahalino+V0.31.html" V0.31/Mahalino+V0.31.html; then
  echo "ERROR: standalone V0.31 build differs from repository version."
  exit 1
fi
cleanup_standalone
trap - EXIT

# The new release must identify itself as V0.31, keep an independent local
# storage key, and leave V0.30 byte-for-byte at its pre-migration tree.
node V0.31/qa/check-release-identity.cjs >"$result_dir/release-identity.json"
# Static resources must exist and must not be zero-byte placeholders.
node V0.31/qa/check-assets.cjs >"$result_dir/asset-manifest.json"

python3 -m http.server 8731 --bind 127.0.0.1 --directory V0.31 >"$result_dir/http-server.log" 2>&1 &
server_pid=$!
trap 'kill "$server_pid" 2>/dev/null || true' EXIT
ready=0
for _attempt in $(seq 1 35); do
  if curl -fsS "$QA_BASE_URL" -o /dev/null; then ready=1; break; fi
  sleep 1
done
if test "$ready" -ne 1; then
  echo "ERROR: local HTTP server did not serve the exact V0.31 HTML"
  exit 1
fi

failed_suites=0
for suite in smoke-v031.js e2e-functional.js e2e-conversational.js v031-browser-regressions.cjs e2e-acceptance-v031.cjs e2e-scenarios-v031.cjs e2e-full-journeys-v031.cjs e2e-guided-usability-v031.cjs e2e-deterministic-guidance-v031.cjs; do
  echo "========= $suite ========="
  if node "V0.31/qa/$suite" >"$result_dir/$suite.log" 2>&1; then
    echo "PASS $suite"
  else
    echo "FAIL $suite"
    failed_suites=$((failed_suites+1))
  fi
  tail -n 30 "$result_dir/$suite.log"
done
if node V0.31/qa/check-coverage.cjs >"$result_dir/coverage-gate.log" 2>&1; then
  echo "PASS machine-readable §19.1 coverage gate"
else
  echo "FAIL mandatory §19.1 coverage gate"
  failed_suites=$((failed_suites+1))
fi
tail -n 12 "$result_dir/coverage-gate.log"
echo "Release gate: $failed_suites failing suite(s)."
if test "$failed_suites" -ne 0; then
  echo "REFUSING PUBLICATION: every QA suite must pass."
  exit 1
fi
echo "ALL GATES PASS: V0.31 may be published."
