#!/usr/bin/env bash
# V0.32 acceptance and release gate. Only a zero exit code permits publication.
set -Eeuo pipefail
repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$repo_root"
result_dir="${QA_RESULTS_DIR:-$repo_root/V0.32/qa/results}"
mkdir -p "$result_dir"
export QA_RESULTS_DIR="$result_dir"
export QA_BASE_URL="${QA_BASE_URL:-http://127.0.0.1:8731/Mahalino%2BV0.32.html}"

# Catch malformed JS even in code paths not reached by browser tests.
for js in V0.32/build_v032.js V0.32/build/*.cjs V0.32/src/*.js V0.32/src/legacy/*.js V0.32/qa/smoke-v032.js V0.32/qa/e2e-*.js V0.32/qa/*.cjs; do
  node --check "$js"
done
node --test V0.32/qa/check-priority-audit.test.cjs V0.32/qa/check-assembler.test.cjs V0.32/qa/check-build-cli.test.cjs
node V0.32/qa/check-refactor-parity.cjs
node V0.32/qa/check-guidance.cjs
node V0.32/qa/check-build-injection.cjs
node V0.32/qa/check-investment-extraction.cjs
node V0.32/qa/check-guided-results.cjs
node V0.32/qa/check-optional-needs.cjs
node V0.32/qa/check-service-context.cjs
node V0.32/qa/check-neighborhood-comparison.cjs
node V0.32/qa/check-optional-service-reports.cjs
node V0.32/qa/check-preference-contracts.cjs
node V0.32/qa/check-project-scope.cjs

# Every V0.32 artifact must be regenerated by the checked-in build and match it.
node V0.32/build_v032.js --check
# A dirty checkout is acceptable only for local diagnostics explicitly opted in
# by the developer; CI never opts in and therefore must test committed output.
if [[ "${QA_ALLOW_DIRTY_WORKTREE:-0}" != 1 ]] && ! git diff --quiet -- V0.32/Mahalino+V0.32.html; then
  echo "ERROR: V0.32 HTML differs from reproducible build output. Commit both sources and generated HTML."
  git diff --stat -- V0.32/Mahalino+V0.32.html
  exit 1
fi

# Standalone archive contract: only V0.32/templates + V0.32/src + build files.
# This intentionally does NOT provide ../V0.29, catching hidden dependencies.
standalone_dir="$(mktemp -d)"
cleanup_standalone(){
  if [[ -n "$standalone_dir" && "$standalone_dir" != / && -d "$standalone_dir" ]]; then
    rm -rf -- "$standalone_dir"
  fi
}
trap cleanup_standalone EXIT
mkdir -p "$standalone_dir/V0.32"
cp V0.32/build_v032.js V0.32/build-manifest.json "$standalone_dir/V0.32/"
cp -R V0.32/src V0.32/templates V0.32/build "$standalone_dir/V0.32/"
node "$standalone_dir/V0.32/build_v032.js"
if ! cmp -s "$standalone_dir/V0.32/Mahalino+V0.32.html" V0.32/Mahalino+V0.32.html; then
  echo "ERROR: standalone V0.32 build differs from repository version."
  exit 1
fi
cleanup_standalone
trap - EXIT

# The new release must identify itself as V0.32, keep an independent local
# storage key, and leave V0.31 byte-for-byte at its source tree.
node V0.32/qa/check-release-identity.cjs >"$result_dir/release-identity.json"
# Static resources must exist and must not be zero-byte placeholders.
node V0.32/qa/check-assets.cjs >"$result_dir/asset-manifest.json"

python3 -m http.server 8731 --bind 127.0.0.1 --directory V0.32 >"$result_dir/http-server.log" 2>&1 &
server_pid=$!
trap 'kill "$server_pid" 2>/dev/null || true' EXIT
ready=0
for _attempt in $(seq 1 35); do
  if curl -fsS "$QA_BASE_URL" -o /dev/null; then ready=1; break; fi
  sleep 1
done
if test "$ready" -ne 1; then
  echo "ERROR: local HTTP server did not serve the exact V0.32 HTML"
  exit 1
fi

failed_suites=0
for suite in smoke-v032.js e2e-functional.js e2e-conversational.js v032-browser-regressions.cjs e2e-acceptance-v032.cjs e2e-scenarios-v032.cjs e2e-full-journeys-v032.cjs e2e-guided-usability-v032.cjs e2e-deterministic-guidance-v032.cjs e2e-priority-audit-v032.cjs; do
  echo "========= $suite ========="
  if node "V0.32/qa/$suite" >"$result_dir/$suite.log" 2>&1; then
    echo "PASS $suite"
  else
    echo "FAIL $suite"
    failed_suites=$((failed_suites+1))
  fi
  tail -n 30 "$result_dir/$suite.log"
done
if node V0.32/qa/check-coverage.cjs >"$result_dir/coverage-gate.log" 2>&1; then
  echo "PASS machine-readable §19.1 coverage gate"
else
  echo "FAIL mandatory §19.1 coverage gate"
  failed_suites=$((failed_suites+1))
fi
tail -n 12 "$result_dir/coverage-gate.log"
# Independent §7/§8 audit coverage; historical §19.1 gate above stays mandatory.
if node V0.32/qa/check-priority-audit.cjs >"$result_dir/priority-audit-gate.log" 2>&1; then
  echo "PASS §7/§8 priority audit coverage gate"
else
  echo "FAIL §7/§8 priority audit coverage gate (missing/failed/unverified evidence blocks release)"
  failed_suites=$((failed_suites+1))
fi
tail -n 12 "$result_dir/priority-audit-gate.log"
echo "Release gate: $failed_suites failing suite(s)."
if test "$failed_suites" -ne 0; then
  echo "REFUSING PUBLICATION: every QA suite must pass."
  exit 1
fi
echo "ALL GATES PASS: V0.32 may be published."
